"""
DevLens AI - Structured Onboarding Document Schema
Defines the schema for machine-validated onboarding dossiers generated by DevLensAgent.
"""

from typing import Any, Literal
from pydantic import BaseModel, Field


class QuickStartInfo(BaseModel):
    install_command: str = Field(default="", description="Command to install dependencies, e.g. npm install, pip install -e .")
    run_command: str | None = Field(default=None, description="Command to run the dev server or application")
    test_command: str | None = Field(default=None, description="Command to run tests, e.g. make test, pytest")
    test_command_type: str = Field(default="declared", description="Whether test command was declared or inferred")
    env_variables: list[str] = Field(default_factory=list, description="Verified env variable keys")


class FolderMapItem(BaseModel):
    path: str = Field(description="Folder path relative to repository root")
    role: str = Field(description="Architectural responsibility of this folder")
    file_count: int = Field(default=0, description="Total files in this directory")
    sample_files: str = Field(default="", description="Representative files in this folder")


class CarefulFileItem(BaseModel):
    path: str = Field(description="File path in repository")
    risk_level: str = Field(default="Medium", description="Computed risk level")
    dependents_count: int = Field(default=0, description="Total downstream dependents")
    source_dependents_count: int = Field(default=0, description="Source code modules importing this file")
    test_dependents_count: int = Field(default=0, description="Test files importing this file")
    coupling: float = Field(default=0.0, description="Coupling score (0.0 to 1.0)")
    reason: str = Field(default="", description="Why this file has a high blast radius and how to verify changes")


class GotchaItem(BaseModel):
    title: str = Field(description="Trap or architectural constraint title")
    description: str = Field(description="Explanation of the constraint or invariant")
    evidence_path: str = Field(description="Repository file proving this constraint exists")


class StarterTaskItem(BaseModel):
    path: str = Field(description="Candidate starter file path")
    line_count: int = Field(default=0, description="Lines of code")
    source_dependents_count: int = Field(default=0, description="Downstream source dependents")
    nearby_test: str | None = Field(default=None, description="Path to associated test file")
    verified_purpose: str = Field(default="purpose not verified", description="Purpose strictly verified from code snippet, or 'purpose not verified'")


class FirstTaskSection(BaseModel):
    title: str = Field(default="Explore Low-Risk Modules", description="Suggested starter initiative title")
    suggested_files: list[StarterTaskItem] = Field(default_factory=list, description="Candidate files with low blast radius")
    rationale: str = Field(default="", description="Why these files are safe Day 1 PRs")
    verification_steps: str = Field(default="", description="Exact steps/commands to verify changes")


class GlossaryItem(BaseModel):
    term: str = Field(description="Codebase term, acronym, or key domain symbol")
    definition: str = Field(description="Explanation grounded in repository code")
    defined_in: str = Field(description="File path where this term or symbol is defined or used")


class OnboardingDocSchema(BaseModel):
    repo_name: str = Field(description="Full repository name owner/repo")
    summary: str = Field(description="1-2 paragraphs describing what this project is and its high-level architecture")
    tech_stack: list[str] = Field(default_factory=list, description="Runtime and dev dependencies")
    quick_start: QuickStartInfo = Field(description="Verified setup and execution commands")
    folder_map: list[FolderMapItem] = Field(default_factory=list, description="High-level directory map")
    how_it_works: str = Field(description="Step-by-step description of data and control flow through entry points")
    careful_files: list[CarefulFileItem] = Field(default_factory=list, description="High-blast-radius junction files")
    gotchas: list[GotchaItem] = Field(default_factory=list, description="Repository-specific invariants and traps")
    first_task: FirstTaskSection = Field(description="Recommended first task for a new contributor")
    glossary: list[GlossaryItem] = Field(default_factory=list, description="Domain and architecture glossary")
